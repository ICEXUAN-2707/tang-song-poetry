/**
 * 按类别快速筛选诗词。
 * @param {string} category - "tang" | "song"
 * @returns {Array<Object>}
 */
function getPoemsByCategory(category) {
    return POEMS.filter((poem) => poem.category === category);
}

/**
 * 根据 ID 查找单首诗词。
 * @param {string} id
 * @returns {Object | undefined}
 */
function getPoemById(id) {
    return POEMS.find((poem) => poem.id === id);
}

/**
 * 全文模糊搜索：标题、作者、朝代、诗句。
 * @param {string} keyword
 * @returns {Array<Object>}
 */
function searchPoems(keyword) {
    const q = keyword.trim().toLowerCase();
    if (!q) return [];
    return POEMS.filter(
        (poem) =>
            poem.title.toLowerCase().includes(q) ||
            poem.author.toLowerCase().includes(q) ||
            poem.dynasty.toLowerCase().includes(q) ||
            poem.content.toLowerCase().includes(q)
    );
}
